from pathlib import Path
CACHE = 'cache-ev-cn-3'
_ROOT = Path(__file__).resolve().parent.parent


def S(page, title, quote, authority='official'):
    """Источник: url берётся из первой строки сохранённой страницы."""
    file = _ROOT / (f'{page}.txt' if '/' in page else f'{CACHE}/{page}.txt')
    url = file.read_text('utf-8').split('\n', 1)[0].strip()
    return {'title': title, 'url': url, 'quote': quote, 'authority': authority, 'page': page}


def C(zh, gloss=None, ru=None, ref=None):
    cell = {'zh': zh}
    if ru:
        cell['ru'] = ru
    if ref:
        cell['ref'] = ref
    if gloss:
        cell['gloss'] = gloss
    return cell


