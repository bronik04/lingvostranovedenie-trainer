def embed(n, target, table, row, ask, where=None, exclude=None):
    fact = {'table': table, 'row': row, 'ask': ask}
    if where:
        fact['where'] = where
    q = {'id': next_id(), 'embeds': target, 'status': 'draft', 'fact': fact}
    if exclude:
        q['exclude'] = exclude
    Q.append(q)


